from typing import Dict, Any, List, Optional
from fastapi import APIRouter, HTTPException, Depends
from pydantic import BaseModel, Field

from auth import get_optional_user
from db.workflow_repository import WorkflowRepository
from utils.rag_terminal_logger import RAGTerminalLogger

router = APIRouter(prefix="/api/workflows", tags=["Workflows"])


class CanvasLogPayload(BaseModel):
    workflow_name: str
    node_count: int
    edge_count: int
    mermaid_code: str


class WorkflowPayload(BaseModel):
    name: str = Field(..., min_length=1, max_length=255, description="Name of the workflow")
    description: Optional[str] = Field("", description="Optional workflow summary/description")
    system_prompt_prefix: Optional[str] = Field("", description="Custom system prompt injected before default instructions")
    nodes: List[Dict[str, Any]] = Field(default_factory=list, description="Visual canvas nodes")
    edges: List[Dict[str, Any]] = Field(default_factory=list, description="Connections between node ports")
    mermaid_code: Optional[str] = Field("", description="Mermaid diagram string representation")
    is_active: Optional[bool] = Field(True, description="Whether workflow is active")


class WorkflowUpdatePayload(BaseModel):
    name: Optional[str] = None
    description: Optional[str] = None
    system_prompt_prefix: Optional[str] = None
    nodes: Optional[List[Dict[str, Any]]] = None
    edges: Optional[List[Dict[str, Any]]] = None
    mermaid_code: Optional[str] = None
    is_active: Optional[bool] = None


@router.get("", summary="List user workflows")
async def list_user_workflows(
    user: Dict[str, Any] = Depends(get_optional_user),
) -> Dict[str, Any]:
    """Retrieves all workflows for the authenticated user or guest session."""
    user_id = user.get("user_id") if user.get("authenticated") else None
    workflows = WorkflowRepository.get_user_workflows(user_id=user_id)
    return {
        "success": True,
        "workflows": workflows,
        "count": len(workflows),
    }


@router.post("", summary="Create a new workflow")
async def create_workflow(
    payload: WorkflowPayload,
    user: Dict[str, Any] = Depends(get_optional_user),
) -> Dict[str, Any]:
    """Creates a new workflow on the visual canvas."""
    user_id = user.get("user_id") if user.get("authenticated") else None
    workflow = WorkflowRepository.create_workflow(
        user_id=user_id,
        name=payload.name,
        description=payload.description or "",
        system_prompt_prefix=payload.system_prompt_prefix or "",
        nodes=payload.nodes,
        edges=payload.edges,
        mermaid_code=payload.mermaid_code or "",
    )
    return {
        "success": True,
        "message": "Workflow created successfully.",
        "workflow": workflow,
    }


@router.get("/{workflow_id}", summary="Get a workflow by ID")
async def get_workflow(
    workflow_id: str,
    user: Dict[str, Any] = Depends(get_optional_user),
) -> Dict[str, Any]:
    """Retrieves details of a specific workflow."""
    user_id = user.get("user_id") if user.get("authenticated") else None
    wf = WorkflowRepository.get_workflow(workflow_id, user_id=user_id)
    if not wf:
        raise HTTPException(status_code=404, detail="Workflow not found")
    return {
        "success": True,
        "workflow": wf,
    }


@router.put("/{workflow_id}", summary="Update an existing workflow")
async def update_workflow(
    workflow_id: str,
    payload: WorkflowUpdatePayload,
    user: Dict[str, Any] = Depends(get_optional_user),
) -> Dict[str, Any]:
    """Updates node layout, configuration, or prompt prefix of a workflow."""
    user_id = user.get("user_id") if user.get("authenticated") else None
    updates = payload.model_dump(exclude_unset=True)
    updated = WorkflowRepository.update_workflow(workflow_id, user_id=user_id, updates=updates)
    if not updated:
        raise HTTPException(status_code=404, detail="Workflow not found")
    return {
        "success": True,
        "message": "Workflow updated successfully.",
        "workflow": updated,
    }


@router.delete("/{workflow_id}", summary="Delete a workflow")
async def delete_workflow(
    workflow_id: str,
    user: Dict[str, Any] = Depends(get_optional_user),
) -> Dict[str, Any]:
    """Deletes a workflow."""
    user_id = user.get("user_id") if user.get("authenticated") else None
    success = WorkflowRepository.delete_workflow(workflow_id, user_id=user_id)
    return {
        "success": success,
        "message": "Workflow deleted successfully.",
    }


@router.post("/log_canvas", summary="Log reactive canvas Mermaid code to coding terminal")
async def log_canvas_code(payload: CanvasLogPayload) -> Dict[str, Any]:
    """Prints the updated Mermaid pipeline code generated by dragging tools on the visual canvas."""
    RAGTerminalLogger.log_agent_builder_canvas_code(
        workflow_name=payload.workflow_name,
        node_count=payload.node_count,
        edge_count=payload.edge_count,
        mermaid_code=payload.mermaid_code,
    )
    return {"success": True}


