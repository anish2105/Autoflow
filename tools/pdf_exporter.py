class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and print total page count ('Page X of Y')
    along with running header and footer.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running Header (pages > 1)
        # AutoFlow watermark header commented out:
        # if self._pageNumber > 1:
        #     self.drawString(36, 756, "AutoFlow System Report | Confidential")
        #     self.setStrokeColor(colors.HexColor("#E2E8F0"))
        #     self.setLineWidth(0.5)
        #     self.line(36, 750, 576, 750)

        # Running Footer (all pages)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(36, 45, 576, 45)

        # AutoFlow watermark footer commented out:
        # gen_date = datetime.now().strftime("%B %d, %Y")
        # self.drawString(36, 32, f"Generated by AutoFlow on {gen_date}")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(576, 32, page_str)
        self.restoreState()


def format_markdown_inline(text: str) -> str:
    """Escapes XML and converts basic inline markdown (bold, italic, code) to ReportLab tags."""
    # First escape & < >
    text = escape(text)
    # Restore bold
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text)
    # Restore italic
    text = re.sub(r'\*(.+?)\*', r'<i>\1</i>', text)
    # Inline code
    text = re.sub(r'`(.+?)`', r'<font face="Courier" color="#0D3273">\1</font>', text)
    return text


def build_pdf_flowables(content: str, title: str, tables_data: Optional[List[Dict[str, Any]]] = None) -> List[Any]:
    """Parse text and tables into ReportLab flowables adhering to:
    - Justified body text
    - Bold headers
    - Professional, styled tables with auto-wrapped text
    """
    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#0D3273'),
        spaceAfter=6,
        alignment=TA_LEFT
    )

    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#64748B'),
        spaceAfter=14
    )

    h1_style = ParagraphStyle(
        'Header1',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=13,
        leading=17,
        textColor=colors.HexColor('#0D3273'),
        spaceBefore=14,
        spaceAfter=6,
        keepWithNext=True
    )

    h2_style = ParagraphStyle(
        'Header2',
        parent=styles['Heading3'],
        fontName='Helvetica-Bold',
        fontSize=11,
        leading=15,
        textColor=colors.HexColor('#1E3A8A'),
        spaceBefore=10,
        spaceAfter=4,
        keepWithNext=True
    )

    body_justified = ParagraphStyle(
        'BodyJustified',
        parent=styles['BodyText'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=14.5,
        textColor=colors.HexColor('#1E293B'),
        alignment=TA_JUSTIFY,
        spaceAfter=8
    )

    bullet_style = ParagraphStyle(
        'BulletJustified',
        parent=body_justified,
        leftIndent=14,
        firstLineIndent=-10,
        spaceAfter=4
    )

    th_style = ParagraphStyle(
        'TableHeader',
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=11,
        textColor=colors.white,
        alignment=TA_CENTER
    )

    td_style = ParagraphStyle(
        'TableCell',
        fontName='Helvetica',
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor('#1E293B'),
        alignment=TA_LEFT
    )

    flowables = []

    # Title & Subtitle
    flowables.append(Paragraph(escape(title), title_style))
    now_str = datetime.now().strftime("%B %d, %Y | %I:%M %p")
    # AutoFlow watermark subtitle commented out:
    # flowables.append(Paragraph(f"AutoFlow Intelligence Report &bull; {now_str}", subtitle_style))
    flowables.append(Paragraph(f"{now_str}", subtitle_style))
    flowables.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#0D3273'), spaceAfter=14))

    # Explicit tables passed as JSON / dicts
    if tables_data:
        for t_info in tables_data:
            t_title = t_info.get("title", "Data Table")
            flowables.append(Paragraph(escape(t_title), h2_style))
            headers = t_info.get("headers", [])
            rows = t_info.get("rows", [])
            if headers or rows:
                t_flowable = create_reportlab_table(headers, rows, th_style, td_style)
                if t_flowable:
                    flowables.append(t_flowable)
                    flowables.append(Spacer(1, 10))

    # Parse lines from markdown content
    lines = content.split('\n')
    i = 0
    in_code_block = False
    code_lines = []

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # Handle code blocks
        if stripped.startswith('```'):
            if in_code_block:
                # Close code block
                code_text = "<br/>".join(escape(c) for c in code_lines)
                code_style = ParagraphStyle(
                    'CodeBox',
                    fontName='Courier',
                    fontSize=8,
                    leading=11,
                    textColor=colors.HexColor('#0F172A')
                )
                code_p = Paragraph(code_text, code_style)
                code_table = Table([[code_p]], colWidths=[540])
                code_table.setStyle(TableStyle([
                    ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F1F5F9')),
                    ('BOX', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
                    ('TOPPADDING', (0,0), (-1,-1), 6),
                    ('BOTTOMPADDING', (0,0), (-1,-1), 6),
                    ('LEFTPADDING', (0,0), (-1,-1), 8),
                    ('RIGHTPADDING', (0,0), (-1,-1), 8),
                ]))
                flowables.append(code_table)
                flowables.append(Spacer(1, 8))
                code_lines = []
                in_code_block = False
            else:
                in_code_block = True
                code_lines = []
            i += 1
            continue

        if in_code_block:
            code_lines.append(line)
            i += 1
            continue

        if not stripped:
            i += 1
            continue

        # Check for Markdown table: lines with '|'
        if stripped.startswith('|') and '|' in stripped[1:]:
            table_lines = []
            while i < len(lines) and lines[i].strip().startswith('|'):
                table_lines.append(lines[i].strip())
                i += 1
            parsed_table = parse_markdown_table_lines(table_lines, th_style, td_style)
            if parsed_table:
                flowables.append(parsed_table)
                flowables.append(Spacer(1, 10))
            continue

        # Headings
        if stripped.startswith('### '):
            h_text = format_markdown_inline(stripped[4:])
            flowables.append(Paragraph(h_text, h2_style))
        elif stripped.startswith('## '):
            h_text = format_markdown_inline(stripped[3:])
            flowables.append(Paragraph(h_text, h1_style))
        elif stripped.startswith('# '):
            h_text = format_markdown_inline(stripped[2:])
            flowables.append(Paragraph(h_text, title_style))
        # Bullet list
        elif stripped.startswith('- ') or stripped.startswith('* ') or re.match(r'^\d+\.\s', stripped):
            item_text = re.sub(r'^([*\-]\s+|\d+\.\s+)', '', stripped)
            formatted = format_markdown_inline(item_text)
            bullet_prefix = "&bull; " if (stripped.startswith('- ') or stripped.startswith('* ')) else ""
            flowables.append(Paragraph(f"{bullet_prefix}{formatted}", bullet_style))
        # Divider
        elif stripped in ('---', '***', '___'):
            flowables.append(Spacer(1, 4))
            flowables.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#E2E8F0'), spaceAfter=8))
        # Standard Body Paragraph (Justified)
        else:
            formatted = format_markdown_inline(stripped)
            flowables.append(Paragraph(formatted, body_justified))

        i += 1

    return flowables


def parse_markdown_table_lines(lines: List[str], th_style, td_style) -> Optional[Table]:
    """Parse raw markdown table lines into a styled ReportLab Table."""
    if len(lines) < 2:
        return None

    raw_matrix = []
    for line in lines:
        cells = [c.strip() for c in line.strip('|').split('|')]
        raw_matrix.append(cells)

    # Check for separator row (e.g. |---|---|)
    if len(raw_matrix) > 1 and all(re.match(r'^:?-+:?$', c) for c in raw_matrix[1] if c):
        headers = raw_matrix[0]
        data_rows = raw_matrix[2:]
    else:
        headers = raw_matrix[0]
        data_rows = raw_matrix[1:]

    return create_reportlab_table(headers, data_rows, th_style, td_style)


def create_reportlab_table(headers: List[str], rows: List[List[str]], th_style, td_style) -> Optional[Table]:
    """Generate a clean, styled ReportLab table flowable with cell paragraph wrapping."""
    if not headers and not rows:
        return None

    num_cols = max(len(headers), max((len(r) for r in rows), default=0))
    if num_cols == 0:
        return None

    # Pad headers & rows to match col count
    clean_headers = headers + [""] * (num_cols - len(headers))
    clean_rows = [r + [""] * (num_cols - len(r)) for r in rows]

    total_width = 540.0
    col_width = total_width / num_cols

    table_data = []
    # Header row
    if headers:
        h_row = [Paragraph(format_markdown_inline(str(h)), th_style) for h in clean_headers]
        table_data.append(h_row)

    # Data rows
    for r in clean_rows:
        row_cells = [Paragraph(format_markdown_inline(str(c)), td_style) for c in r]
        table_data.append(row_cells)

    if not table_data:
        return None

    t = Table(table_data, colWidths=[col_width] * num_cols, repeatRows=1 if headers else 0)
    t_style = [
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0D3273')),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
    ]

    # Alternating row background
    for row_idx in range(1 if headers else 0, len(table_data)):
        if row_idx % 2 == 1:
            t_style.append(('BACKGROUND', (0, row_idx), (-1, row_idx), colors.HexColor('#F8FAFC')))
        else:
            t_style.append(('BACKGROUND', (0, row_idx), (-1, row_idx), colors.HexColor('#FFFFFF')))

    t.setStyle(TableStyle(t_style))
    return t


def sanitize_filename(name: str) -> str:
    clean = re.sub(r'[^\w\-_.]', '_', name.strip().lower())
    clean = re.sub(r'_+', '_', clean).strip('_')
    return clean[:50] or "export"


def create_pdf_export(
    content: str,
    title: str = "Report",
    tables_json: Optional[Union[str, List[Dict[str, Any]], Dict[str, Any], Any]] = None,
    conversation_id: Optional[str] = None
) -> Dict[str, Any]:
    """In-memory generation of PDF export, returning Base64 record stored in database."""
    parsed_tables = None
    if tables_json:
        if isinstance(tables_json, list):
            parsed_tables = tables_json
        elif isinstance(tables_json, dict):
            parsed_tables = [tables_json]
        elif isinstance(tables_json, str):
            try:
                parsed_tables = json.loads(tables_json)
                if isinstance(parsed_tables, dict):
                    parsed_tables = [parsed_tables]
            except Exception:
                pass

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=54,
        bottomMargin=54
    )

    flowables = build_pdf_flowables(content=content, title=title, tables_data=parsed_tables)
    doc.build(flowables, canvasmaker=NumberedCanvas)

    pdf_bytes = buffer.getvalue()
    buffer.close()

    b64_content = base64.b64encode(pdf_bytes).decode('utf-8')
    timestamp_suffix = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_title = sanitize_filename(title)
    filename = f"{safe_title}_{timestamp_suffix}.pdf"

    record = ExportRepository.save_export(
        title=title,
        filename=filename,
        file_type="pdf",
        mime_type="application/pdf",
        content_base64=b64_content,
        size_bytes=len(pdf_bytes),
        conversation_id=conversation_id
    )
    return record


@tool
def export_chat_pdf(
    content: str,
    title: str = "Report",
    tables_json: Optional[Union[str, List[Dict[str, Any]], Dict[str, Any], Any]] = None,
    conversation_id: Optional[str] = None
) -> str:
    """Export conversation content, analysis, or structured tables into a polished, professional PDF document.
    Use ONLY when the user explicitly requests to export, generate, or download content as a PDF or report.
    PDF formatting standards enforced: Justified body text, bold headers, and styled tables with cell wrapping.

    Args:
        content: The text content, markdown, or chat transcript to export.
        title: The title of the PDF report (e.g. 'Fall 2026 Admissions Evaluation').
        tables_json: Optional JSON string or list of structured tables [{'title': '...', 'headers': [...], 'rows': [[...]]}].
        conversation_id: Optional UUID of the conversation thread.
    """
    try:
        record = create_pdf_export(
            content=content,
            title=title,
            tables_json=tables_json,
            conversation_id=conversation_id
        )
        export_id = record["id"]
        filename = record["filename"]
        size_kb = round(record["size_bytes"] / 1024, 2)
        download_url = f"/api/exports/download/{export_id}"

        return (
            f"### Document Exported Successfully (PDF)\n\n"
            f"- **Title**: {title}\n"
            f"- **Filename**: `{filename}`\n"
            f"- **File Size**: {size_kb} KB\n"
            f"- **Format**: PDF Document (`.pdf`)\n\n"
            f"[Download PDF Document]({download_url})"
        )
    except Exception as e:
        return f"Failed to export PDF: {str(e)}"
