def sanitize_filename(name: str) -> str:
    clean = re.sub(r'[^\w\-_.]', '_', name.strip().lower())
    clean = re.sub(r'_+', '_', clean).strip('_')
    return clean[:50] or "export"


def sanitize_sheet_title(name: str) -> str:
    # Excel worksheet title max 31 chars, no invalid chars : \ / ? * [ ]
    clean = re.sub(r'[:\\/?*\[\]]', ' ', name.strip())
    clean = re.sub(r'\s+', ' ', clean).strip()
    return clean[:31] or "Sheet1"


def parse_markdown_tables_from_text(text: str) -> List[Dict[str, Any]]:
    """Extract markdown tables and preceding headings from markdown text."""
    lines = text.split('\n')
    tables = []
    current_title = "Data Table"
    i = 0

    while i < len(lines):
        line = lines[i].strip()
        if line.startswith('#'):
            current_title = line.lstrip('#').strip()
        elif line.startswith('|') and '|' in line[1:]:
            tbl_lines = []
            while i < len(lines) and lines[i].strip().startswith('|'):
                tbl_lines.append(lines[i].strip())
                i += 1

            if len(tbl_lines) >= 2:
                raw_matrix = []
                for tl in tbl_lines:
                    cells = [c.strip() for c in tl.strip('|').split('|')]
                    raw_matrix.append(cells)

                if len(raw_matrix) > 1 and all(re.match(r'^:?-+:?$', c) for c in raw_matrix[1] if c):
                    headers = raw_matrix[0]
                    rows = raw_matrix[2:]
                else:
                    headers = raw_matrix[0]
                    rows = raw_matrix[1:]

                tables.append({
                    "title": current_title,
                    "headers": headers,
                    "rows": rows
                })
            continue
        i += 1
    return tables


def style_worksheet(ws, title: str, headers: List[str], rows: List[List[Any]]):
    """Format an openpyxl worksheet strictly to specifications:
    - Bold, center-aligned headers
    - No gridlines (showGridLines = False)
    - Auto-fitted column widths
    - Alternating zebra row shading
    - Clean borders
    """
    # 1. Explicitly disable gridlines
    ws.views.sheetView[0].showGridLines = False

    # Styles
    navy_fill = PatternFill(start_color="0D3273", end_color="0D3273", fill_type="solid")
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    header_alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    zebra_fill = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")
    white_fill = PatternFill(start_color="FFFFFF", end_color="FFFFFF", fill_type="solid")
    data_font = Font(name="Calibri", size=10, color="1E293B")
    
    thin_border_side = Side(style='thin', color='CBD5E1')
    cell_border = Border(
        left=thin_border_side,
        right=thin_border_side,
        top=thin_border_side,
        bottom=thin_border_side
    )

    # Title Banner (Row 1-2)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=max(len(headers), 4))
    title_cell = ws.cell(row=1, column=1)
    title_cell.value = title.upper()
    title_cell.font = Font(name="Calibri", size=13, bold=True, color="0D3273")
    title_cell.alignment = Alignment(horizontal="left", vertical="center")
    ws.row_dimensions[1].height = 25

    # Subtitle with timestamp
    # AutoFlow watermark commented out:
    # ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=max(len(headers), 4))
    # sub_cell = ws.cell(row=2, column=1)
    # sub_cell.value = f"Generated by AutoFlow Agent • {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
    # sub_cell.font = Font(name="Calibri", size=9, italic=True, color="64748B")
    # sub_cell.alignment = Alignment(horizontal="left", vertical="center")
    # ws.row_dimensions[2].height = 18

    # Blank Row 3
    ws.row_dimensions[3].height = 10

    # Headers at Row 4
    header_row_idx = 4
    ws.row_dimensions[header_row_idx].height = 28

    for col_idx, h_text in enumerate(headers, start=1):
        cell = ws.cell(row=header_row_idx, column=col_idx)
        cell.value = str(h_text)
        cell.font = header_font
        cell.fill = navy_fill
        cell.alignment = header_alignment
        cell.border = cell_border

    # Data Rows starting at Row 5
    start_data_row = 5
    for r_idx, row_data in enumerate(rows, start=start_data_row):
        ws.row_dimensions[r_idx].height = 22
        is_zebra = (r_idx % 2 == 1)
        row_fill = zebra_fill if is_zebra else white_fill

        for c_idx in range(1, len(headers) + 1):
            val = row_data[c_idx - 1] if c_idx - 1 < len(row_data) else ""
            cell = ws.cell(row=r_idx, column=c_idx)
            cell.value = val
            cell.font = data_font
            cell.fill = row_fill
            cell.border = cell_border

            # Number or short text alignment
            str_val = str(val).strip()
            if str_val.isdigit() or (len(str_val) <= 6 and not any(ch.isalpha() for ch in str_val)):
                cell.alignment = Alignment(horizontal="center", vertical="center")
            else:
                cell.alignment = Alignment(horizontal="left", vertical="center", wrap_text=True)

    # Auto-fit Column Widths with safety margin
    for col_idx in range(1, len(headers) + 1):
        col_letter = get_column_letter(col_idx)
        max_len = 0
        for row in range(header_row_idx, start_data_row + len(rows)):
            val_str = str(ws.cell(row=row, column=col_idx).value or "")
            max_len = max(max_len, len(val_str))
        ws.column_dimensions[col_letter].width = min(max(max_len + 4, 14), 50)


def create_excel_export(
    content: str = "",
    title: str = "Excel Spreadsheet",
    sheets_json: Optional[Union[str, List[Dict[str, Any]], Dict[str, Any], Any]] = None,
    conversation_id: Optional[str] = None
) -> Dict[str, Any]:
    """In-memory generation of Excel workbook stored as Base64 in database."""
    wb = openpyxl.Workbook()
    # Remove default sheet
    default_sheet = wb.active

    parsed_sheets = []
    if sheets_json:
        if isinstance(sheets_json, list):
            parsed_sheets = sheets_json
        elif isinstance(sheets_json, dict):
            parsed_sheets = [sheets_json]
        elif isinstance(sheets_json, str):
            try:
                parsed = json.loads(sheets_json)
                if isinstance(parsed, list):
                    parsed_sheets = parsed
                elif isinstance(parsed, dict):
                    parsed_sheets = [parsed]
            except Exception:
                pass

    # If no explicit sheets JSON, parse tables from markdown content
    if not parsed_sheets and content:
        md_tables = parse_markdown_tables_from_text(content)
        for t in md_tables:
            parsed_sheets.append({
                "sheet_name": t.get("title", "Data Table"),
                "headers": t.get("headers", []),
                "rows": t.get("rows", [])
            })

    # If still no sheets, create a default transcript sheet
    if not parsed_sheets:
        lines = [l for l in content.split('\n') if l.strip()]
        rows = [[f"Item {idx+1}", line] for idx, line in enumerate(lines)]
        parsed_sheets.append({
            "sheet_name": "Summary",
            "headers": ["Index", "Conversation Notes & Details"],
            "rows": rows
        })

    # Create worksheets
    for s_idx, s_info in enumerate(parsed_sheets):
        sheet_title = sanitize_sheet_title(s_info.get("sheet_name") or f"Sheet_{s_idx+1}")
        ws = wb.create_sheet(title=sheet_title)
        headers = s_info.get("headers", ["Column 1"])
        rows = s_info.get("rows", [])
        style_worksheet(ws, title=s_info.get("sheet_name", title), headers=headers, rows=rows)

    # Clean up initial default sheet
    if default_sheet in wb.worksheets and len(wb.worksheets) > 1:
        wb.remove(default_sheet)

    # Save to in-memory buffer
    buffer = io.BytesIO()
    wb.save(buffer)
    excel_bytes = buffer.getvalue()
    buffer.close()

    b64_content = base64.b64encode(excel_bytes).decode('utf-8')
    timestamp_suffix = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_title = sanitize_filename(title)
    filename = f"{safe_title}_{timestamp_suffix}.xlsx"

    record = ExportRepository.save_export(
        title=title,
        filename=filename,
        file_type="xlsx",
        mime_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        content_base64=b64_content,
        size_bytes=len(excel_bytes),
        conversation_id=conversation_id
    )
    return record


@tool
def export_chat_excel(
    content: str = "",
    title: str = "Excel Spreadsheet",
    sheets_json: Optional[Union[str, List[Dict[str, Any]], Dict[str, Any], Any]] = None,
    conversation_id: Optional[str] = None
) -> str:
    """Export tables, comparisons, profile evaluations, or structured data into a polished Excel spreadsheet (.xlsx).
    Use ONLY when the user explicitly requests to export, generate, or download content as an Excel file or spreadsheet.
    Excel formatting standards enforced: Bold center-aligned headers, auto-fitted columns, alternating zebra rows, and NO gridlines.

    Args:
        content: Markdown content containing markdown tables or transcript text to export.
        title: The title of the workbook (e.g. 'Fall 2026 University Shortlist').
        sheets_json: Optional JSON string or structured list specifying custom sheets [{'sheet_name': '...', 'headers': [...], 'rows': [[...]]}].
        conversation_id: Optional UUID of the conversation thread.
    """
    try:
        record = create_excel_export(
            content=content,
            title=title,
            sheets_json=sheets_json,
            conversation_id=conversation_id
        )
        export_id = record["id"]
        filename = record["filename"]
        size_kb = round(record["size_bytes"] / 1024, 2)
        download_url = f"/api/exports/download/{export_id}"

        return (
            f"### Spreadsheet Exported Successfully (Excel)\n\n"
            f"- **Title**: {title}\n"
            f"- **Filename**: `{filename}`\n"
            f"- **File Size**: {size_kb} KB\n"
            f"- **Format**: Excel Spreadsheet (`.xlsx`)\n"
            f"- **Formatting**: Bold center-aligned headers, alternating rows, and gridlines removed.\n\n"
            f"[Download Excel Spreadsheet]({download_url})"
        )
    except Exception as e:
        return f"Failed to export Excel spreadsheet: {str(e)}"
