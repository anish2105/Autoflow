import io
import base64
import re
from datetime import datetime
from typing import Optional, Dict, Any
from langchain_core.tools import tool
from db.export_repository import ExportRepository


def sanitize_filename(name: str) -> str:
    """Sanitize title into a safe filename."""
    clean = re.sub(r'[^\w\-_.]', '_', name.strip().lower())
    clean = re.sub(r'_+', '_', clean).strip('_')
    return clean[:50] or "export"


def create_txt_export(
    content: str,
    title: str = "AutoFlow Chat Export",
    conversation_id: Optional[str] = None
) -> Dict[str, Any]:
    """In-memory generation of Plain Text chat export stored as Base64 in database."""
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    timestamp_suffix = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_title = sanitize_filename(title)
    filename = f"{safe_title}_{timestamp_suffix}.txt"

    buffer = io.StringIO()
    buffer.write("=" * 80 + "\n")
    buffer.write(f"  {title.upper()}\n")
    buffer.write(f"  Generated by AutoFlow Agent | {now_str}\n")
    buffer.write("=" * 80 + "\n\n")

    # Clean content
    buffer.write(content.strip() + "\n\n")
    buffer.write("-" * 80 + "\n")
    buffer.write("End of AutoFlow Chat Export\n")

    raw_text = buffer.getvalue()
    raw_bytes = raw_text.encode("utf-8")
    b64_content = base64.b64encode(raw_bytes).decode("utf-8")

    record = ExportRepository.save_export(
        title=title,
        filename=filename,
        file_type="txt",
        mime_type="text/plain; charset=utf-8",
        content_base64=b64_content,
        size_bytes=len(raw_bytes),
        conversation_id=conversation_id,
    )
    return record


@tool
def export_chat_txt(
    content: str,
    title: str = "AutoFlow Conversation Export",
    conversation_id: Optional[str] = None
) -> str:
    """Export conversation content or LLM responses as a plain text (.txt) file.
    Use ONLY when the user explicitly asks to export, dump, or download content as text or txt.
    
    Args:
        content: The text content or chat transcript to export.
        title: The title of the exported document.
        conversation_id: Optional UUID of the conversation thread.
    """
    try:
        record = create_txt_export(content=content, title=title, conversation_id=conversation_id)
        export_id = record["id"]
        filename = record["filename"]
        size_kb = round(record["size_bytes"] / 1024, 2)
        download_url = f"/api/exports/download/{export_id}"

        return (
            f"### Chat Exported Successfully (Plain Text)\n\n"
            f"- **Filename**: `{filename}`\n"
            f"- **File Size**: {size_kb} KB\n"
            f"- **Format**: Plain Text (`.txt`)\n\n"
            f"[Download Text File]({download_url})"
        )
    except Exception as e:
        return f"Failed to export chat as plain text: {str(e)}"
